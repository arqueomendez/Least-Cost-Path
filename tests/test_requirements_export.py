"""Anclas de regresion de S15: requirements.txt debe ser un export fiel de uv.lock."""

import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _lock_versions():
    lock = tomllib.loads((ROOT / "uv.lock").read_text(encoding="utf-8"))
    pinned = set()
    for pkg in lock["package"]:
        pinned.add((pkg["name"].lower(), pkg["version"]))
    return pinned, {pkg["name"].lower() for pkg in lock["package"]}


def _requirement_pins():
    pins = []
    for line in (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines():
        if line.startswith("#") or "==" not in line:
            continue
        spec = line.split("#")[0].strip().rstrip("\\").strip()
        name, rest = spec.split("==", 1)
        pins.append((name.strip().lower(), rest.split(";")[0].split()[0].strip()))
    return pins


def test_s15_requirements_pins_match_uv_lock():
    """S15: every pinned version in requirements.txt exists in uv.lock."""
    locked, names = _lock_versions()
    pins = _requirement_pins()
    assert pins, "requirements.txt has no pins"
    assert [p for p in pins if p not in locked] == []
    assert {n for n, _ in pins} <= names


def test_s15_requirements_header_records_command():
    """S15: header still records the generating command."""
    head = (ROOT / "requirements.txt").read_text(encoding="utf-8").splitlines()[:2]
    assert head[0].startswith("# This file was autogenerated by uv")
    assert "uv export --format requirements-txt" in head[1]
